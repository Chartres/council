export const PERSONA_BY_ID = new Map(PERSONAS.map((p) => [p.id, p]))

/**
 * Ticking rules: up to MAX_PERSONAS at once, never an empty council. Pure so the
 * cap has a test that does not need a rendered picker.
 */
export function nextPicked(current: string[], id: string): string[] {
  if (current.includes(id)) {
    return current.length > 1 ? current.filter((p) => p !== id) : current
  }
  return current.length >= MAX_PERSONAS ? current : [...current, id]
}

export const DEFAULT_PERSONA_IDS = PERSONAS.filter((p) => p.defaultOn).map((p) => p.id)

/** Fallback for a persona id the gateway sends that this build doesn't know. */
export function personaName(id: string): string {
  return PERSONA_BY_ID.get(id)?.name ?? id
}

export function personaMonogram(id: string): string {
  return PERSONA_BY_ID.get(id)?.monogram ?? id.slice(0, 2).toUpperCase()
}

