// The roster. Ids are the gateway contract's `personas[]` values; the gateway owns
// the persona bible (prompts never ship to the client). Sources are public domain.
// No Jesus in v1 (build spec, 2026-10-07). Monograms, never portraits — the
// Montessori estate's non-affiliation line depends on it.

export interface Persona {
  id: string
  name: string
  /** Stylised monogram — initials, not a face. */
  monogram: string
  /** One line: what they bring to the table. */
  brings: string
  /** Public-domain source the gateway's persona bible is built from. */
  source: string
  /** Ticked on first load. */
  defaultOn: boolean
}

